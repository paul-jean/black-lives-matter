#!/usr/bin/env python3
"""Convert data/victims.csv into docs/js/data.js for the offline app.

Run after editing the CSV:

    python3 scripts/build_data.py

The CSV columns are: Name, birth, death, age
Dates are written like "Feb 5 1995".
"""
import csv
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "victims.csv"
OUT = ROOT / "docs" / "js" / "data.js"


def parse_date(text):
    return datetime.strptime(text.strip(), "%b %d %Y").date()


def main():
    victims = []
    with SRC.open(newline="", encoding="utf-8") as f:
        reader = csv.reader(f, skipinitialspace=True)
        next(reader)  # header
        for i, row in enumerate(reader, start=1):
            if not row or not row[0].strip():
                continue
            name, birth, death, age = (c.strip() for c in row)
            birth_d, death_d = parse_date(birth), parse_date(death)
            if death_d < birth_d:
                sys.exit(f"Row {i} ({name}): death date is before birth date")
            victims.append(
                {
                    "id": i,
                    "name": name,
                    "birth_date": birth_d.isoformat(),
                    "death_date": death_d.isoformat(),
                    "age": int(age),
                }
            )

    names = [v["name"] for v in victims]
    if len(names) != len(set(names)):
        sys.exit("Duplicate names in CSV; names are used as page keys")

    body = json.dumps(victims, indent=2, ensure_ascii=False)
    OUT.write_text(
        "// Generated by scripts/build_data.py from data/victims.csv. Do not edit by hand.\n"
        f"window.VICTIMS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(victims)} records to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
